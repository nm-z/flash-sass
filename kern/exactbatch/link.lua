-- Combine current scalar operator bodies with the imported B8 framework/ops.
local function read(p) local f=assert(io.open(p,"rb"));local s=f:read("a");f:close();return s end
local function write(p,s) local f=assert(io.open(p,"wb"));assert(f:write(s));assert(f:close()) end
local function once(s,a,b)
 local i,j=assert(s:find(a,1,true));j=i+#a-1
 assert(not s:find(a,j+1,true),"duplicate anchor "..a)
 return s:sub(1,i-1)..b..s:sub(j+1)
end
local base=read(assert(arg[1]));local header=read(assert(arg[2]));local dir=assert(arg[3])
local output=assert(arg[4]);local hout=assert(arg[5])
local scalar={};for n in assert(header:match("die_opname%[%].-%{(.-)%}")):gmatch('"([%w_]+)"') do scalar[#scalar+1]=n end
assert(#scalar==tonumber(header:match("#define OP_COUNT (%d+)")),"scalar opcode count")
local tags={"bf16bias8","bf16k25608","bf16k3208","bf16hc8","bf16hcx8",
 "q2k25608","q2k6408","q2acc6408","q2moegn8","q2moedn8","bf16hcup8",
 "q3kk25608","q3kk61448","dnstep8","actq2568","rms25608"}
local maps={};local started=false
for line in assert(base:match("<REGISTER_MAPPING>(.-)</REGISTER_MAPPING>")):gmatch("[^\n]+") do
 if line:match(":%s*embrow_") then started=true end
 if started then maps[#maps+1]=line.."\n" end
end
assert(started)
local a=assert(base:find("\nembrow_SETUP:\n",1,true))
local b=assert(base:find("\nPOSITION_END:\n",a,true))
local body=base:sub(a+1,b)
local extra=read(dir.."/operators.sass")
maps[#maps+1]=assert(extra:match("<REGISTER_MAPPING>(.-)</REGISTER_MAPPING>"))
extra=extra:gsub("<REGISTER_MAPPING>.-</REGISTER_MAPPING>","")
local names={};for _,n in ipairs(scalar) do names[#names+1]=n end
for _,n in ipairs(tags) do names[#names+1]=n end
local dispatch={"OP_DISPATCH:\n",string.format("--:-:-:-:6      ISETP.GE.U32.AND P6, PT, op, 0x%x, PT;\n",#names),
 "--:-:-:-:6      SHL fw0, op, 0x5;\n--:-:-:-:6      NOP;\n--:-:-:-:6      NOP;\n",
 "--:-:-:-:6  @P6 BRA POSITION_END;\n--:-:-:-:6      BRX fw0 DISPATCH_TABLE;\nDISPATCH_TABLE:\n"}
for _,n in ipairs(names) do dispatch[#dispatch+1]="--:-:-:-:6      BRA "..n.."_SETUP;\n--:-:-:-:6      NOP;\n--:-:-:-:6      NOP;\n" end
dispatch[#dispatch+1]="--:-:-:-:6      BRA POSITION_END;\n"
local frame=read(dir.."/frame.sass")
frame=once(frame,"# EXACT_OPERATOR_MAP",table.concat(maps))
frame=once(frame,"# EXACT_DISPATCH",table.concat(dispatch))
frame=once(frame,"# EXACT_OPERATOR_BODY",body.."\n"..extra)
write(output,"# Kernel: die\n"..frame)
local h={"/* Generated by exactbatch/link.lua. */\n#ifndef FLASH_EXACT_OPS_H\n#define FLASH_EXACT_OPS_H\n#include \"dieops.h\"\n"}
for i,n in ipairs(tags) do h[#h+1]=string.format("#define OP_%s %d\n",n:upper(),#scalar+i-1) end
h[#h+1]=string.format("#define EXACT_OP_COUNT %d\n#endif\n",#names)
write(hout,table.concat(h))
