# d = a * b + c (32 x 32 -> low 32); x is a temporary, d must differ from a
def mul(d, a, b, c, x)
  "--:-:-:-:6      XMAD.MRG #{x}, #{a}, #{b}.H1, RZ;\n" \
  "--:-:-:-:6      XMAD #{d}, #{a}, #{b}, #{c};\n" \
  "--:-:-:-:6      XMAD.PSL.CBCC #{d}, #{a}.H1, #{x}.H1, #{d};\n"
end

def kloop(cg)
  s = +''
  64.times { |k| s << format("--:-:-:-:1      BFE.U32 wv%02d, q%d, 0x%x;\n", k, k / 16, (2 << 8) | (2 * (k % 16))) }
  64.times { |k| s << format("--:-:-:-:1      IADD wv%02d, wv%02d, mag;\n", k, k) }
  64.times { |k| s << format("--:-:-:-:1      FADD wv%02d, wv%02d, moff;\n", k, k) }
  buf = ->(k) { k.even? ? 'x' : 'xb' }
  bar = ->(k) { k.even? ? 5 : 6 }
  lds = ->(k) { (cg / 4).times.map { |j| format("--:-:%d:-:1      LDS.U.128 %s%02d, [sm+0x%x];\n", bar.(k), buf.(k), 4 * j, 64 * k + 16 * j) }.join }
  s << lds.(0)
  64.times do |k|
    s << lds.(k + 1) if k < 63
    cg.times do |c|
      acc = cg == 4 && k.odd? ? format('sb%d', c) : format('s%02d', c)
      first = cg == 4 ? k < 2 : k.zero?
      w = c.zero? ? format('%02x', 1 << (bar.(k) - 1)) : '--'
      s << (first ? format("%s:-:-:-:1      FMUL %s, wv%02d, %s%02d;\n", w, acc, k, buf.(k), c)
                  : format("%s:-:-:-:1      FFMA %s, wv%02d, %s%02d, %s;\n", w, acc, k, buf.(k), c, acc))
    end
  end
  s << "--:-:-:-:6      NOP;\n"
  4.times { |c| s << format("--:-:-:-:1      FADD s%02d, s%02d, sb%d;\n", c, c, c) } if cg == 4
  s << "--:-:-:-:6      NOP;\n" if cg == 4
  cg.times { |c| s << format("%s:-:-:-:1      FFMA acc%02d, dsc, s%02d, acc%02d;\n", c.zero? ? '08' : '--', c, c, c) }
  s
end
# the three loops, chosen by cgw (uniform per CTA)
def kloops(tag)
  "--:-:-:-:6      ISETP.EQ.U32.AND P0, PT, cgw, 0x10, PT;\n--:-:-:-:6      ISETP.EQ.U32.AND P1, PT, cgw, 0x8, PT;\n" \
  "--:-:-:-:6      NOP;\n--:-:-:-:6      NOP;\n--:-:-:-:6      NOP;\n--:-:-:-:6  @P0 BRA K16#{tag};\n--:-:-:-:6  @P1 BRA K8#{tag};\n" +
    kloop(4) + "--:-:-:-:6      BRA KE#{tag};\nK8#{tag}:\n" + kloop(8) + "--:-:-:-:6      BRA KE#{tag};\nK16#{tag}:\n" + kloop(16) + "KE#{tag}:\n"
end
