# Standalone forms of the existing arithmetic bodies for a CUDA graph.
# Launch dependencies replace interpreter dispatch, grid barriers and flag polls.
use strict;
use warnings;
sub graph_build {
    my ($ops) = @_;
    mkdir 'graph-ops' unless -d 'graph-ops';
    my %position = (embrow=>0x150,conv1d=>0x160,attnqk=>0x190,
        attnqkq=>0x190,idxqk=>0x188,idxscore=>0x160,idxsel=>0x158,
        kvgather=>0x178,attnpart=>0x170,attnpartn=>0x170,
        amax=>0x170,sample=>0x170,plerows=>0x168,pleconv=>0x168);
    open my $ptx,'>','graph-ops/ops.ptx' or die $!;
    print $ptx ".version 7.4\n.target sm_52\n.address_size 64\n";
    open my $header,'>','graphops.h' or die $!;
    print $header "/* generated by die.pl graph */\nstatic const unsigned graph_threads[] = {\n";
    for my $op (@$ops) {
        my ($tag,$file,$kind,$env) = @$op;
        print $header $kind eq 'cta' ? "256,\n" : "32,\n";
        next if $tag =~ /^(?:bf16biasp|bf16k2560p|bf16k320p|bf16hcp|bf16hcxp|xwait)$/;
        local %ENV = (%ENV,%$env);
        delete @ENV{qw(DIE_T0_OFF DIE_EXP_OFF)};
        open my $src,'<',$file or die "$file: $!";
        my $text = do { local $/; <$src> }; close $src;
        $text =~ s/#.*$//mg;
        1 while $text =~ s|<CODE>(.*?)</CODE>|my $s=eval "package MaxAs::MaxAs::CODE; $1"; die "$file: $@" if $@; $s|se;
        my $pro = "--:-:-:-:6      MEMBAR.GL.IVALLD;\n";
        my $max=-1;
        while ($text =~ /^\s*(\d+(?:[-,]\d+)*)\s*:/mg) {
            for my $r (split /[-,]/,$1) { $max=$r if $r>$max; }
        }
        my @params;
        while ($text =~ /^\s*(\w+)\s*:\s*c\[0x0\]\[0x([0-9a-f]+)\]/mg) {
            push @params,[$1,hex $2];
        }
        my $registers='';
        for my $p (@params) {
            my ($name,$addr)=@$p;
            $text =~ s/^(\s*)\Q$name\E(\s*:\s*c\[)/$1 . 'graph_arg_' . $name . $2/me;
            $registers .= '    '.(++$max)." : $name\n";
            $pro .= "--:-:-:-:6      MOV $name, graph_arg_$name;\n";
        }
        if (exists $position{$tag}) {
            my $addr=sprintf '%x',$position{$tag};
            my ($param)=map {$_->[0]} grep {$_->[1]==$position{$tag}} @params;
            die "$tag: missing position parameter at $addr" unless $param;
            my $ptr=($max+2)&~1; my $pos=$ptr+2;
            die "$tag: no dynamic position registers" if $pos>254;
            $text =~ s|</CONSTANT_MAPPING>|    graph_ctl0 : c[0x0][0x1b8]\n    graph_ctl1 : c[0x0][0x1bc]\n</CONSTANT_MAPPING>|;
            $registers .= "    $ptr,@{[$ptr+1]} : graph_cp<0-1>\n    $pos : graph_position\n";
            $pro .= "--:-:-:-:6      MOV graph_cp0, graph_ctl0;\n--:-:-:-:6      MOV graph_cp1, graph_ctl1;\n";
            $pro .= "--:-:6:-:2      LDG.E.CV graph_position, [graph_cp+0x8];\n20:-:-:-:6      IADD $param, $param, graph_position;\n";
        }
        die "$tag: register overflow" if $max>254;
        $text =~ s|</REGISTER_MAPPING>|$registers</REGISTER_MAPPING>|;
        $text =~ s|(</REGISTER_MAPPING>)|$1\n$pro| or die "$tag: missing mapping";
        # Complete all outstanding stores before publishing completion to graph
        # successors, including successors in a peer device context.
        $text =~ s/EXIT;/BRA GRAPH_DONE;/g;
        $text .= "\nGRAPH_DONE:\n3f:-:-:-:6      MEMBAR.SYS;\n--:-:-:-:f      EXIT;\n";
        open my $sass,'>',"graph-ops/$tag.sass" or die $!;
        print $sass "# Kernel: graph_$tag\n",$text;close $sass;
        print $ptx ".visible .entry graph_$tag(.param .align 8 .b8 words[120], .param .u64 ctl)\n{\n.shared .align 16 .b8 smem[49152];\n.reg .u32 %r;\nld.param.u32 %r, [words];\nst.shared.u32 [smem], %r;\nret;\n}\n";
    }
    print $ptx <<'PTX';
.visible .entry graph_advance(.param .align 8 .b8 controls[48])
{
    .reg .u64 %c<6>;
    .reg .u32 %n, %stop;
    ld.param.u64 %c0, [controls];
    ld.param.u64 %c1, [controls+8];
    ld.param.u64 %c2, [controls+16];
    ld.param.u64 %c3, [controls+24];
    ld.param.u64 %c4, [controls+32];
    ld.param.u64 %c5, [controls+40];
    ld.global.u32 %n, [%c0+8];
    ld.global.u32 %stop, [%c0+20];
    add.u32 %n, %n, 1;
    or.b32 %n, %n, %stop;
    st.global.wt.u32 [%c0+8], %n;
    st.global.wt.u32 [%c1+8], %n;
    st.global.wt.u32 [%c2+8], %n;
    st.global.wt.u32 [%c3+8], %n;
    st.global.wt.u32 [%c4+8], %n;
    st.global.wt.u32 [%c5+8], %n;
    membar.sys;
    ret;
}
PTX
    print $header "};\n";close $header;close $ptx;
}
1;
